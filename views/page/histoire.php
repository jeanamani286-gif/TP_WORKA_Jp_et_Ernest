      <p class="sous-titre">Les réponses officielles des archives Wonka — avec une marge d'interprétation.</p>
      <details open>
        <summary>Pourquoi l'usine a-t-elle fermé pendant douze ans ?</summary>
        <p>Après le vol des recettes en 1978, Willy Wonka a fermé les portes pour protéger ses inventions. Les machines ont continué à fonctionner, mais uniquement le mardi et sans témoin.</p>
      </details>
      <details>
        <summary>Peut-on visiter les lieux historiques sans Golden Ticket ?</summary>
        <p>Non. Le Golden Ticket est indispensable pour entrer dans l'usine et découvrir ses archives. Le musée interne n'ouvre qu'aux visiteurs de la <a href="visite-usine.html">visite guidée</a>.</p>
      </details>
      <details>
        <summary>Les recettes originales sont-elles encore utilisées ?</summary>
        <p>Une seule recette est restée parfaitement secrète. Les autres ont été modernisées, testées, puis parfois retirées après qu'un bonbon a demandé un avocat.</p>
      </details>
      <details>
        <summary>Que s'est-il vraiment passé en 1983 ?</summary>
        <p>Les archives officielles parlent d'une année manquante. La version la plus probable est qu'elles ont servi à emballer des confiseries. La version de Wonka est beaucoup plus longue et contient un tunnel.</p>
